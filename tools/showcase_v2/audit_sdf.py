"""Render current production glyph functions against cached true LaTeX SVGs.

This diagnostic uses desktop GL, not Minecraft. It does not rebuild TeX or
change production assets. The SVG cache is generated by build_type.py.
"""
from __future__ import annotations

import argparse
import importlib.util
import io
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import cairosvg
import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/showcase"))
_spec = importlib.util.spec_from_file_location("_sdf_audit_renderer", ROOT / "tools/showcase/render_film.py")
_shared = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_shared)
FilmRenderer = _shared.FilmRenderer


def vector(values):
    return "vec%d(%s)" % (len(values), ",".join("%.9f" % value for value in values))


def glyph_shader(glyphs):
    """Use actual source functions; u remains live even for identical endpoints."""
    source = (ROOT / "tools/showcase_v2/film.fragment").read_text(encoding="utf-8")
    prefix = source.split("// __GEOMETRY__")[0]
    calls = []
    for glyph in glyphs:
        values = ",".join(vector(glyph[key]) for key in ("center", "size", "tile"))
        calls.append("glyph(c,p,%s,%s,EXTRA_VECTOR1.x,0.0,vec3(1.0),1.0,aa);" % (values, values))
    return prefix + """
void main() {
    vec2 p=vec2((uv.x-0.5)*EXTRA_VECTOR1.y,0.5-uv.y)*9.0;
    float aa=9.0/EXTRA_VECTOR1.z;
    vec3 c=vec3(0.0);
""" + "\n".join(calls) + "\n    gl_FragColor=vec4(c,1.0);\n}\n"


def scaled_glyphs(group, height, width):
    scale = min(height, width / group["width"])
    return [{"tile": glyph["tile"], "center": [v * scale for v in glyph["center"]],
             "size": [v * scale for v in glyph["size"]]} for glyph in group["glyphs"]]


def svg_reference(svg_path, group, height, width):
    scale = min(height, width / group["width"])
    x0, y0, x1, y1 = group["raw_bounds"]
    pixels_per_unit = scale / (y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    svg = ET.fromstring(svg_path.read_text(encoding="utf-8"))
    svg.attrib.update(viewBox=" ".join(str(v) for v in
                                      [cx - 8 / pixels_per_unit, cy - 4.5 / pixels_per_unit,
                                       16 / pixels_per_unit, 9 / pixels_per_unit]),
                      preserveAspectRatio="none")
    png = cairosvg.svg2png(bytestring=ET.tostring(svg), output_width=3840, output_height=2160)
    return Image.open(io.BytesIO(png)).getchannel("A").resize((1920, 1080), Image.Resampling.LANCZOS)


def audit(assets, texture, output):
    output.mkdir(parents=True, exist_ok=True)
    metadata = json.loads((assets / "type_data.json").read_text(encoding="utf-8"))
    report, contact = {}, Image.new("RGB", (2960, 1640), (8, 16, 25))
    samples = [("quadratic1", 1.7, 11.5), ("fourier2", 1.35, 12.5),
               ("matrix1", .95, 3.0), ("algebra1", 1.7, 11.5)]
    for row, (name, height, width) in enumerate(samples):
        group = metadata["groups"][name]
        reference = svg_reference(assets / "svg" / (name + ".svg"), group, height, width)
        path = output / (name + ".fragment")
        path.write_text(glyph_shader(scaled_glyphs(group, height, width)), encoding="utf-8")
        renderer = FilmRenderer(path, texture, 1920, 1080)
        try:
            images = [renderer.image(u) for u in (0, .5, 1)]
        finally:
            renderer.close()
        target = np.asarray(reference) / 255.
        actual = np.asarray(images[0])[:, :, 0] / 255.
        left, right = target > .5, actual > .5
        report[name] = {
            "ink_iou_50": float((left & right).sum() / (left | right).sum()),
            "outside_reference_pixels_over_5pct": int(((actual > .05) & (target < .01)).sum()),
            "unchanged_glyph_u0_u05_u1_maxdiff": max(int(np.abs(np.asarray(image).astype(int)
                                                      - np.asarray(images[0]).astype(int)).max())
                                                     for image in images),
        }
        reference.save(output / (name + "-reference.png"))
        for index, image in enumerate(images):
            image.save(output / (name + "-u" + str(index) + ".png"))
        for column, image in enumerate((reference.convert("RGB"), images[0])):
            contact.paste(image.crop((220, 350, 1700, 730)), (column * 1480, row * 410 + 30))
            ImageDraw.Draw(contact).text((column * 1480 + 10, row * 410 + 8),
                                         name + (" / true SVG" if column == 0 else " / current shader"), fill="white")
    contact.save(output / "contact.png")
    (output / "results.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, default=ROOT / ".runtime/showcase-v2")
    parser.add_argument("--texture", type=Path, default=ROOT / "resource_pack/textures/manim/client_showcase.png")
    parser.add_argument("--output", type=Path, default=ROOT / ".runtime/showcase-sdf-audit")
    args = parser.parse_args()
    print(json.dumps(audit(args.assets, args.texture, args.output), indent=2))
