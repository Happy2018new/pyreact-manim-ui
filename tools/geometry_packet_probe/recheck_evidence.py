"""Reopen geometry-probe PNG/state evidence and independently audit every slot.

Run with --evidence PATH. The compact independent-verification.json preserves
failed source cases as well as completed cases. Saved .verify.json files are
not trusted or reused: expected bytes are regenerated by the host seed oracle.
This checks captured on-screen output; it is not GPU readback to game Python,
verification of every render frame, or a physical-mobile-hardware measurement.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
import re

from PIL import Image

from verify_capture import verify_image, verify_reports


HERE = Path(__file__).resolve().parent
IDENTITY_KEYS = ("schema", "seed", "generation", "slot_count", "geometry_name",
                 "geometry_build_serial")
SUMMARY_KEYS = ("payload_bytes", "checked_cells", "capture_count", "full_slot_coverage",
                "observed_payload_sha256", "expected_payload_sha256")


def _sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _read_json(path):
    raw = path.read_bytes()
    data = json.loads(raw.decode("utf-8-sig"))
    if not isinstance(data, dict):
        raise ValueError("JSON evidence must be an object: " + path.name)
    return data, _sha(raw)


def _same_identity(left, right):
    return all(left.get(key) == right.get(key) for key in IDENTITY_KEYS)


def _capture_provenance(path, capture_path):
    provenance, digest = _read_json(path)
    required = {"ok": True, "backend": "Windows.Graphics.Capture", "native_resolution": True,
                "width": 720, "height": 1080, "background_only": True}
    if any((provenance.get(key) is not value if isinstance(value, bool)
            else provenance.get(key) != value) for key, value in required.items()):
        raise ValueError("capture provenance does not establish native background WGC")
    requested, captured = provenance.get("request_qpc_100ns"), provenance.get("frame_qpc_100ns")
    if (any(isinstance(value, bool) or not isinstance(value, int) or value < 0
            for value in (requested, captured)) or captured < requested):
        raise ValueError("WGC frame timestamp predates its request")
    if Path(provenance.get("file", "")).resolve() != capture_path.resolve():
        raise ValueError("capture provenance names a different PNG")
    window = provenance.get("window")
    if (not isinstance(window, dict) or window.get("minimized") is not False or
            window.get("pid") != provenance.get("pid") or
            any(isinstance(window.get(key), bool) or not isinstance(window.get(key), int) or
                window[key] < 1 for key in ("pid", "hwnd"))):
        raise ValueError("capture window identity is invalid or minimized")
    for phase in ("background_before", "background_after"):
        state = provenance.get(phase)
        if (not isinstance(state, dict) or state.get("background_safe") is not True or
                state.get("window_noactivate") is not True or
                not isinstance(state.get("foreground"), dict) or
                state["foreground"].get("pid") == window.get("pid")):
            raise ValueError("capture did not preserve background noactivation: " + phase)
        entries = state.get("windows")
        if not isinstance(entries, list) or any(not isinstance(entry, dict) for entry in entries):
            raise ValueError("capture background window list is malformed: " + phase)
        matching = [entry for entry in entries
                    if entry.get("pid") == window.get("pid") and entry.get("hwnd") == window["hwnd"]]
        if (len(matching) != 1 or matching[0].get("noactivate") is not True or
                matching[0].get("minimized") is not False):
            raise ValueError("capture background window identity is inconsistent: " + phase)
    return digest


def recheck_case(case_path, evidence):
    """Return a failure-preserving audit row; never modify original evidence."""
    row = {"case": case_path.relative_to(evidence).as_posix(), "passed": False,
           "source_status": "unreadable", "verified_windows": 0, "verified_bytes": 0,
           "checked_bytes": 0, "failure_reasons": [], "windows": []}
    try:
        raw_case = case_path.read_bytes()
        row["case_sha256"] = _sha(raw_case)
        case = json.loads(raw_case.decode("utf-8-sig"))
        if not isinstance(case, dict):
            raise ValueError("case JSON must be an object")
        row.update(name=case.get("name"), source_status=case.get("status"),
                   declared_payload_bytes=case.get("payload_bytes"),
                   dynamic=case.get("dynamic"), source_error=case.get("error"))
        if case.get("status") == "failed":
            row["failure_reasons"].append("source_case_failed: " + str(case.get("error")))
            return row
        if case.get("status") != "completed":
            raise ValueError("source case status must be completed or failed")
        if case.get("stage") != "completed" or case.get("error") is not None:
            raise ValueError("completed case has an unfinished stage or nonnull error")
        for key in ("gpu_to_python_readback", "all_render_frames_verified", "actual_mobile_hardware"):
            if case.get(key) is not False:
                row["failure_reasons"].append("unsupported or missing evidence-boundary flag: " + key)
        name = case.get("name")
        if (not isinstance(name, str) or re.fullmatch(r"[a-z0-9_]+", name) is None or
                case_path.name != name + ".case.json"):
            raise ValueError("case name must match its safe evidence filename")
        windows = case.get("windows")
        if not isinstance(windows, list) or not windows:
            raise ValueError("completed case must declare a nonempty windows list")
        payload_bytes = case.get("payload_bytes")
        if isinstance(payload_bytes, bool) or not isinstance(payload_bytes, int) or payload_bytes < 1:
            raise ValueError("case payload_bytes must be a positive integer")
        folder = case_path.parent
        labels = [name + "_window_%04d" % index for index in range(len(windows))]
        for suffix in (".state.json", ".png"):
            declared = {label + suffix for label in labels}
            found = {path.name for path in folder.glob(name + "_window_*" + suffix)}
            if declared != found:
                row["failure_reasons"].append(
                    "window_file_set_mismatch %s: missing=%s extra=%s" %
                    (suffix, sorted(declared - found), sorted(found - declared)))
        frozen, frozen_sha = _read_json(folder / (name + "_frozen.state.json"))
        row["frozen_state_sha256"] = frozen_sha
        if frozen.get("benchmark_running") is not False:
            row["failure_reasons"].append("frozen snapshot still has a running benchmark")
        if frozen.get("ready") is not True:
            row["failure_reasons"].append("frozen snapshot does not have a ready screen")
        if frozen.get("slot_count") != payload_bytes:
            row["failure_reasons"].append("frozen slot_count differs from case payload_bytes")
        final = case.get("final_snapshot")
        if not isinstance(final, dict) or not _same_identity(frozen, final):
            row["failure_reasons"].append("final snapshot differs from frozen geometry identity")
        pairs = []
        for ordinal, label in enumerate(labels):
            state_path, capture_path = folder / (label + ".state.json"), folder / (label + ".png")
            window = {"index": ordinal, "state": state_path.relative_to(evidence).as_posix(),
                      "capture": capture_path.relative_to(evidence).as_posix(), "passed": False}
            try:
                state, state_sha = _read_json(state_path)
                window["state_sha256"] = state_sha
                raw_capture = capture_path.read_bytes()
                window["capture_sha256"] = _sha(raw_capture)
                window["capture_provenance_sha256"] = _capture_provenance(
                    folder / (label + ".json"), capture_path)
                with Image.open(io.BytesIO(raw_capture)) as source:
                    image = source.convert("RGBA")
                report = verify_image(state, image)
                pairs.append((state, report))
                window.update(query=report["query"], checked_bytes=report["checked_cells"],
                              failed_cells=report["failed_cells"], max_error=report["max_error"],
                              observed_payload_sha256=report["observed_payload_sha256"],
                              expected_payload_sha256=report["expected_payload_sha256"])
                row["checked_bytes"] += report["checked_cells"]
                errors = []
                if not report["passed"]:
                    errors.append("%d cells failed exact RGB+alpha patch verification" %
                                  report["failed_cells"])
                if (not _same_identity(frozen, state) or state.get("benchmark_running") is not False or
                        state.get("ready") is not True):
                    errors.append("window differs from frozen geometry identity or is still updating")
                recorded = windows[ordinal]
                if not isinstance(recorded, dict):
                    errors.append("case window summary must be an object")
                else:
                    for key in ("query", "checked_cells", "observed_payload_sha256",
                                "expected_payload_sha256"):
                        if recorded.get(key) != report[key]:
                            errors.append("case window summary mismatch: " + key)
                    if recorded.get("passed") is not True:
                        errors.append("completed case includes a nonpassing window summary")
                if errors:
                    raise ValueError("; ".join(errors))
                window["passed"] = True
                row["verified_windows"] += 1
                row["verified_bytes"] += report["checked_cells"]
            except (OSError, ValueError, KeyError, TypeError, OverflowError) as error:
                window["error"] = "%s: %s" % (type(error).__name__, error)
                row["failure_reasons"].append(label + ": " + window["error"])
            row["windows"].append(window)
        try:
            series = verify_reports(pairs)
            row["verification"] = {key: series[key] for key in SUMMARY_KEYS}
            if not series["passed"]:
                row["failure_reasons"].append("full-slot independent pixel verification failed")
            if series["payload_bytes"] != payload_bytes:
                row["failure_reasons"].append("independent byte count differs from case payload_bytes")
            recorded = case.get("verification")
            if not isinstance(recorded, dict):
                row["failure_reasons"].append("completed case is missing verification summary")
            else:
                for key in SUMMARY_KEYS:
                    if recorded.get(key) != series[key]:
                        row["failure_reasons"].append("case verification summary mismatch: " + key)
                if recorded.get("passed") is not True:
                    row["failure_reasons"].append("completed case verification is not marked passing")
        except (ValueError, KeyError, TypeError, OverflowError) as error:
            row["failure_reasons"].append("series: %s: %s" % (type(error).__name__, error))
        if _sha(case_path.read_bytes()) != row["case_sha256"]:
            row["failure_reasons"].append("source case changed during independent audit")
        row["passed"] = not row["failure_reasons"]
    except (OSError, ValueError, KeyError, TypeError, OverflowError) as error:
        row["failure_reasons"].append("%s: %s" % (type(error).__name__, error))
    return row


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, required=True)
    args = parser.parse_args(argv)
    evidence = args.evidence.resolve()
    if not evidence.is_dir():
        parser.error("--evidence must be an existing evidence directory")
    paths = sorted(evidence.rglob("*.case.json"))
    cases = [recheck_case(path, evidence) for path in paths]
    completed = [row for row in cases if row["source_status"] == "completed"]
    verified = [row for row in completed if row["passed"]]
    source_failed = sum(row["source_status"] == "failed" for row in cases)
    report = {
        "schema": "geometry_packet_independent_verification_v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "evidence": str(evidence), "passed": bool(cases) and all(row["passed"] for row in cases),
        "completed_cases_recheck_passed": bool(completed) and len(verified) == len(completed),
        "case_count": len(cases), "source_completed_cases": len(completed),
        "source_failed_cases": source_failed,
        "unreadable_or_other_cases": len(cases) - len(completed) - source_failed,
        "verified_completed_cases": len(verified),
        "failed_completed_rechecks": len(completed) - len(verified),
        "verified_windows": sum(row["verified_windows"] for row in verified),
        "verified_bytes": sum(row["verified_bytes"] for row in verified),
        "scope": "captured_on_screen_output_of_frozen_geometry_queries",
        "gpu_to_python_readback": False, "all_render_frames_verified": False,
        "actual_mobile_hardware": False,
        "limitations": ["On-screen bytes are decoded by host Python from captured pixels.",
                        "No GPU payload is read back into game Python.",
                        "Only recorded frozen query frames are verified, not every benchmark frame.",
                        "Identical overlapping native faces cannot be excluded by pixel equality."],
        "verifier_sha256": _sha(Path(__file__).read_bytes()),
        "pixel_oracle_sha256": _sha((HERE / "verify_capture.py").read_bytes()),
        "cases": cases,
    }
    output = evidence / "independent-verification.json"
    output.write_text(json.dumps(report, ensure_ascii=False, separators=(",", ":")) + "\n",
                      encoding="utf-8")
    print(json.dumps({key: report[key] for key in
                      ("passed", "case_count", "source_completed_cases", "source_failed_cases",
                       "verified_completed_cases", "failed_completed_rechecks", "verified_bytes")},
                     separators=(",", ":")))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
