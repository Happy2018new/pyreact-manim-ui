"""Deploy the authored 41-second film without rebaking the ten reference scenes."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint
import shutil

from build_canvas import read_scenes

ROOT = Path(__file__).resolve().parents[1]
NAME = "client_showcase"


def build(assets=None, root=ROOT):
    root = Path(root).resolve()
    assets = Path(assets) if assets else root / "tools/showcase"
    metadata = json.loads((assets / "typography.json").read_text(encoding="utf-8"))
    atlas = assets / "showcase_atlas.png"
    if assets == root / "tools/showcase":
        atlas = root / "resource_pack/textures/manim/client_showcase.png"
    if metadata["size"] != [2048, 2048] or hashlib.sha256(atlas.read_bytes()).hexdigest() != metadata["sha256"]:
        raise ValueError("Showcase atlas shape or checksum differs from typography metadata")
    constants = []
    for key, label in metadata["labels"].items():
        constants.append("const vec4 TYPE_%s = vec4(%s);" % (
            key.upper(), ", ".join("%.1f" % value for value in label["rect"])))
    source = (root / "tools/showcase/client_showcase.fragment").read_text(encoding="utf-8")
    marker = "// __TYPOGRAPHY_CONSTANTS__"
    if source.count(marker) != 1:
        raise ValueError("Missing showcase typography insertion point")
    shader = source.replace(marker, "\n".join(constants))
    resource = root / "resource_pack"
    shader_path = resource / "shaders/glsl/client_showcase.fragment"
    texture_path = resource / "textures/manim/client_showcase.png"
    material_path = resource / "materials/postprocess.material"
    materials = json.loads(material_path.read_text(encoding="utf-8"))
    materials["pmanim_client_showcase"] = {
        "vertexShader": "shaders/uv_fullscreen.vertex",
        "fragmentShader": "shaders/client_showcase.fragment",
        "vertexFields": [{"field": "Position"}, {"field": "UV0"}],
        "samplerStates": [{"samplerIndex": index, "textureWrap": "Clamp", "textureFilter": "Point"}
                          for index in range(3)],
        "states": ["DisableDepthTest"], "msaaSupport": "Both",
    }
    config = root / "behavior_pack/manim_ui/generated_scenes.py"
    scenes = [scene for scene in read_scenes(config) if scene["name"] != NAME]
    scenes.append({"name": NAME, "title": "作品演示：让想法，成为可见", "duration": 41.0,
                   "material": "pmanim_client_showcase", "post_name": "pmanim_client_showcase",
                   "texture": "textures/manim/client_showcase", "canvas_compatible": False})
    shader_path.write_bytes(shader.encode("utf-8"))
    if atlas.resolve() != texture_path.resolve():
        shutil.copyfile(atlas, texture_path)
    material_path.write_text(json.dumps(materials, indent=2) + "\n", encoding="utf-8", newline="\n")
    config.write_text("# -*- coding: utf-8 -*-\n# Generated by tools/deploy_demo.py and tools/build_showcase.py.\nSCENES = " +
                      pprint.pformat(scenes, width=100, sort_dicts=True) + "\n", encoding="utf-8", newline="\n")
    # Keep the rebuild metadata small: point values already live in the PNG.
    public = {key: value for key, value in metadata.items() if key != "morph"}
    public["morph"] = {key: value for key, value in metadata["morph"].items()
                       if key not in ("source_points", "target_points")}
    public.update(duration=41.0, shader_sha256=hashlib.sha256(shader_path.read_bytes()).hexdigest(),
                  typography_generator="tools/showcase/build_typography.py")
    (root / "tools/showcase/typography.json").write_text(
        json.dumps(public, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    return {"scene": NAME, "duration": 41, "shader_bytes": shader_path.stat().st_size,
            "texture_bytes": texture_path.stat().st_size, "scene_count": len(scenes)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path)
    args = parser.parse_args()
    print(json.dumps(build(args.assets), ensure_ascii=False, indent=2))
