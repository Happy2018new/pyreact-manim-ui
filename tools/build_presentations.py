"""Build both presentation shaders and register them with the game player."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import pprint

from build_canvas import read_scenes
from showcase_v2.build_film import build as build_math
from storybook.build_film import build as build_story

ROOT = Path(__file__).resolve().parents[1]


def register_story():
    manifest = json.loads((ROOT / "tools/storybook/generated/story.json").read_text(encoding="utf-8"))
    path = ROOT / "behavior_pack/manim_ui/generated_scenes.py"
    scenes = [scene for scene in read_scenes(path) if scene["name"] != "story_showcase"]
    scenes.append({"name": "story_showcase", "title": "风之童话：" + manifest["title"], "duration": manifest["duration"],
                   "canvas_compatible": False, "material": "pmanim_story_showcase",
                   "post_name": "pmanim_story_showcase", "texture": "textures/manim/story_showcase"})
    path.write_text("# -*- coding: utf-8 -*-\n# Generated by the scene and presentation builders.\nSCENES = "
                    + pprint.pformat(scenes, width=100, sort_dicts=True) + "\n", encoding="utf-8", newline="\n")
    path = ROOT / "resource_pack/materials/postprocess.material"
    materials = json.loads(path.read_text(encoding="utf-8"))
    materials["pmanim_story_showcase"] = {
        "vertexShader": "shaders/uv_fullscreen.vertex", "fragmentShader": "shaders/story_showcase.fragment",
        "vertexFields": [{"field": "Position"}, {"field": "UV0"}],
        "samplerStates": [{"samplerIndex": i, "textureWrap": "Clamp", "textureFilter": "Point"} for i in range(3)],
        "states": ["DisableDepthTest"], "msaaSupport": "Both"}
    path.write_text(json.dumps(materials, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--math-assets", type=Path)
    args = parser.parse_args()
    build_math(args.math_assets)
    build_story(ROOT / "tools/storybook/generated")
    register_story()
    print("Registered client_showcase and story_showcase", flush=True)
